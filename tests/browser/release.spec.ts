import { test, expect } from '@playwright/test'
const band = { id: 'band-1', slug: 'tobago-carnival', name: 'Tobago Carnival', eventYear: 2026, eventLabel: 'Carnival', tagline: 'Catch the vibe', brand: {}, entitlements: ['truck_tracker','updates','guide'], liveModules: ['truck_tracker','updates','guide'], comingOnline: [], upsells: {}, catalog: [] }
const truck = { name: 'Carnival truck', publicLive: false, status: 'not-live', message: 'Not on the road yet', meetup: { lat:11.18,lng:-60.73,label:'Scarborough — to be confirmed' }, position: null, serverTime: new Date().toISOString() }
test.beforeEach(async ({ page }) => {
  await page.route('**/api/auth/me', r => r.fulfill({ json: { user: null } }))
  await page.route('**/api/public/bands', r => r.fulfill({ json: { bands: [band] } }))
  await page.route('**/api/public/bands/tobago-carnival', r => r.fulfill({ json: { band } }))
  await page.route('**/api/public/bands/tobago-carnival/tracker', r => r.fulfill({ json: { truck } }))
})
test('live route loads without upsell; disconnected tracker hides position', async ({ page }) => {
  await page.goto('/tobago-carnival')
  await expect(page.getByRole('heading', { name: 'Find the truck' })).toBeVisible()
  await expect(page.getByRole('heading', { name: /Not on the road yet/ })).toBeVisible()
  await page.route('**/api/public/bands/tobago-carnival/tracker', r => r.abort())
  await expect(page.getByText('Connection interrupted.', { exact: false })).toBeVisible({ timeout:15000 })
  await expect(page.getByRole('button', { name:'Try again' })).toBeVisible()
})
test('band outages offer retry rather than claiming band does not exist', async ({ page }) => {
  await page.route('**/api/public/bands/tobago-carnival', r => r.fulfill({ status:503, json:{error:{message:'Unavailable'}} }))
  await page.goto('/tobago-carnival')
  await expect(page.getByText('Could not connect.', { exact:false })).toBeVisible()
  await page.route('**/api/public/bands/tobago-carnival', r => r.fulfill({ json:{band} }))
  await page.getByRole('button',{name:'Try again'}).click()
  await expect(page.getByRole('heading',{name:'Find the truck'})).toBeVisible()
})
