test('admin action failures are visible and buttons recover', async ({ page }) => {
  const user = { id:'u', email:'admin@example.test', name:'Admin', platformRole:'platform_admin', bandRoles:[], mustResetPassword:false }
  await page.route('**/api/auth/me', r => r.fulfill({json:{user}}))
  await page.route('**/api/platform/bands?*', r => r.fulfill({json:{bands:[{...band,entitlements:[]}],hasMore:false}}))
  await page.route('**/api/platform/users?*', r => r.fulfill({json:{users:[],hasMore:false}}))
  await page.route('**/api/platform/requests?*', r => r.fulfill({json:{requests:[],hasMore:false}}))
  await page.route('**/api/platform/bands/*/entitlements', r => r.fulfill({status:503,json:{error:{message:'Activation failed. Please retry.'}}}))
  await page.goto('/platform')
  await page.getByRole('button',{name:'Activate',exact:true}).first().click()
  await expect(page.getByText('Activation failed. Please retry.')).toBeVisible()
  await expect(page.getByRole('button',{name:'Activate',exact:true}).first()).toBeEnabled()
})
test('guide falls back to its public cached copy on connection failure', async ({ page }) => {
  await page.route('**/api/public/bands/tobago-carnival/content/guide', r => r.fulfill({json:{content:{title:'Your day',location:'Scarborough',schedule:['To be confirmed'],notes:['Follow your marshal']},updatedAt:new Date().toISOString()}}))
  await page.goto('/tobago-carnival/guide')
  await expect(page.getByText('Follow your marshal')).toBeVisible()
  await page.route('**/api/public/bands/tobago-carnival/content/guide', r => r.abort())
  await page.reload()
  await expect(page.getByText('Offline copy', {exact:false})).toBeVisible()
  await expect(page.getByText('Follow your marshal')).toBeVisible()
})
test('location denial leaves the tracker usable', async ({ page, context }) => {
  await context.clearPermissions()
  await page.goto('/tobago-carnival')
  await page.getByRole('button',{name:'Show my location'}).click()
  await expect(page.getByText('Location was unavailable.',{exact:false})).toBeVisible({timeout:20000})
  await expect(page.getByRole('heading',{name:'Find the truck'})).toBeVisible()
})
